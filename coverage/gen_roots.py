#!/usr/bin/env python3
"""Generate rigorous binary64 enclosures of e((b+1/2)/N) = (cos, sin)(2*pi*(2b+1)/(2N)) for b in 0..N-1,
plus pi, with python-flint arb at 200 bits, outward-rounded to doubles.  Output: a C++ header.
Independent of the search code (which uses its own cis_turns).  Usage: gen_roots.py N out.hpp
"""

import math
import sys
from fractions import Fraction

import flint


def to_frac(a):
    # exact rational enclosure endpoints of an arb from its decimal string with 60 digits, widened by 1e-55
    s = a.str(60, radius=False)
    return Fraction(s)


def round_down(fr):
    f = float(fr)
    while Fraction(f) > fr:
        f = math.nextafter(f, -math.inf)
    return f


def round_up(fr):
    f = float(fr)
    while Fraction(f) < fr:
        f = math.nextafter(f, math.inf)
    return f


def enclose(a):
    eps = Fraction(1, 10**50)
    lo = to_frac(a.lower()) - eps
    hi = to_frac(a.upper()) + eps
    # sanity: the arb's own interval must sit inside
    return round_down(lo), round_up(hi)


def main():
    N = int(sys.argv[1])
    out = sys.argv[2]
    flint.ctx.prec = 200
    pi = flint.arb.pi()
    plo, phi = enclose(pi)
    lines = []
    lines.append(
        "// generated by gen_roots.py: rigorous enclosures of cos/sin(2 pi (2b+1)/(2N)), N=%d, arb prec 200"
        % N
    )
    lines.append("#pragma once")
    lines.append("static const int ROOTS_N = %d;" % N)
    lines.append("static const double PI_LO = %r, PI_HI = %r;" % (plo, phi))
    lines.append("static const double ROOT_COS[%d][2] = {" % N)
    cs = []
    ss = []
    for b in range(N):
        ang = pi * flint.arb(2 * b + 1) / flint.arb(N)  # 2*pi*(2b+1)/(2N)
        c = ang.cos()
        s = ang.sin()
        cl, ch = enclose(c)
        sl, sh = enclose(s)
        assert cl <= ch and sl <= sh and ch - cl < 1e-15 and sh - sl < 1e-15
        # cross-check against libm (non-rigorous, sanity only)
        assert abs(math.cos(math.pi * (2 * b + 1) / N) - cl) < 1e-12
        assert abs(math.sin(math.pi * (2 * b + 1) / N) - sl) < 1e-12
        cs.append("  {%r, %r}," % (cl, ch))
        ss.append("  {%r, %r}," % (sl, sh))
    lines += cs
    lines.append("};")
    lines.append("static const double ROOT_SIN[%d][2] = {" % N)
    lines += ss
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out, "pi in [%r, %r]" % (plo, phi))


if __name__ == "__main__":
    main()
